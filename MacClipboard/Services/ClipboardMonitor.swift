import AppKit
import Combine
import SwiftData

@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published var isIncognito: Bool = false
    
    private var changeCount: Int
    private var timer: Timer?
    private var modelContext: ModelContext
    
    // 排除的密码管理器应用 ID
    private let excludedAppBundleIDs: Set<String> = [
        "com.agilebits.onepassword7",
        "com.1password.1password",
        "com.bitwarden.desktop",
        "com.keepassxc.keepassxc",
        "com.apple.keychainaccess"
    ]
    
    // 排除的剪切板敏感字段类型
    private let sensitiveTypes = [
        "org.nspasteboard.ConcealedType",
        "com.1password.concealed-type",
        "org.nspasteboard.AutoGeneratedType"
    ]

    init(modelContext: ModelContext) {
        self.modelContext = modelContext
        self.changeCount = NSPasteboard.general.changeCount
        startMonitoring()
    }

    func startMonitoring() {
        // 1. 修复 Swift 6 并发安全：使用 Task { @MainActor in } 并安全捕获 self
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkPasteboard()
            }
        }
    }

    private func checkPasteboard() {
        guard !isIncognito else { return }
        
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        
        let frontmostApp = NSWorkspace.shared.frontmostApplication
        if let bundleID = frontmostApp?.bundleIdentifier, AppSettings.shared.excludedBundleIDSet.contains(bundleID) {
            return
        }
        
        let types = pasteboard.types?.map { $0.rawValue } ?? []
        for sensitiveType in sensitiveTypes {
            if types.contains(sensitiveType) { return }
        }
        
        saveClipboardData(from: pasteboard, bundleID: frontmostApp?.bundleIdentifier)
    }

    private func saveClipboardData(from pasteboard: NSPasteboard, bundleID: String?) {
        // 富文本 (RTF)
        if let rtfData = pasteboard.data(forType: .rtf) {
            let text = pasteboard.string(forType: .string) ?? "Rich Text"
            if matchesSensitiveRegex(text) { return }
            let item = ClipboardItem(type: .rtf, textContent: text, rtfData: rtfData, sourceAppBundleID: bundleID)
            insertAndEnforceLimit(item)
            return
        }
        
        // 纯文本/颜色/URL
        if let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty {
            if matchesSensitiveRegex(text) { return }
            
            // HEX 颜色
            if text.range(of: "^#?([A-Fa-f0-9]{6}|[A-Fa-f0-9]{3})$", options: .regularExpression) != nil {
                let hex = text.hasPrefix("#") ? text : "#\(text)"
                let item = ClipboardItem(type: .color, textContent: text, colorHex: hex, sourceAppBundleID: bundleID)
                insertAndEnforceLimit(item)
                return
            }
            
            // URL
            if let url = URL(string: text), url.scheme == "http" || url.scheme == "https" {
                let item = ClipboardItem(type: .url, textContent: text, urlString: text, sourceAppBundleID: bundleID)
                insertAndEnforceLimit(item)
                return
            }
            
            // 普通文本
            let item = ClipboardItem(type: .text, textContent: text, sourceAppBundleID: bundleID)
            insertAndEnforceLimit(item)
            return
        }
        
        // 图片
        if let image = NSImage(pasteboard: pasteboard), let tiffData = image.tiffRepresentation {
            let bitmap = NSBitmapImageRep(data: tiffData)
            let pngData = bitmap?.representation(using: .png, properties: [:])
            let item = ClipboardItem(type: .image, imageData: pngData, sourceAppBundleID: bundleID)
            insertAndEnforceLimit(item)
        }
    }

    private func matchesSensitiveRegex(_ text: String) -> Bool {
        let patterns = AppSettings.shared.sensitiveRegexPatterns
            .components(separatedBy: ",")
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
            
        for pattern in patterns {
            if text.range(of: pattern, options: .regularExpression) != nil {
                return true
            }
        }
        return false
    }

    private func isDuplicate(_ a: ClipboardItem, _ b: ClipboardItem) -> Bool {
        guard a.type == b.type else { return false }
        switch a.type {
        case .text, .color, .url:
            return a.textContent == b.textContent
        case .rtf:
            return a.rtfData == b.rtfData || (a.textContent == b.textContent && a.textContent != nil)
        case .image:
            if let dataA = a.imageData, let dataB = b.imageData {
                return dataA == dataB
            }
            return false
        }
    }

    private func insertAndEnforceLimit(_ item: ClipboardItem) {
        // 去重逻辑：检查最新一条记录是否与当前内容完全一致
        let fetchLatestDescriptor = FetchDescriptor<ClipboardItem>(
            sortBy: [SortDescriptor(\ClipboardItem.createdAt, order: .reverse)]
        )
        if let latestItems = try? modelContext.fetch(fetchLatestDescriptor), let latest = latestItems.first {
            if isDuplicate(latest, item) {
                latest.createdAt = Date()
                try? modelContext.save()
                return
            }
        }

        modelContext.insert(item)
        SoundManager.playCopySound()
        
        let limit = AppSettings.shared.maxHistoryCount
        
        let fetchDescriptor = FetchDescriptor<ClipboardItem>(
            predicate: #Predicate<ClipboardItem> { !$0.isPinned },
            sortBy: [SortDescriptor(\ClipboardItem.createdAt, order: .forward)]
        )
        
        if let unpinnedItems = try? modelContext.fetch(fetchDescriptor), unpinnedItems.count > limit {
            let deleteCount = unpinnedItems.count - limit
            for i in 0..<deleteCount {
                modelContext.delete(unpinnedItems[i])
            }
        }
        
        try? modelContext.save()
    }
}
