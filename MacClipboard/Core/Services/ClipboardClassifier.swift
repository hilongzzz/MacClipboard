import Foundation

/// 剪贴板内容的类型快照：与 NSPasteboard 解耦，便于单元测试。
struct PasteboardSnapshot {
    var typeIdentifiers: [String]
    var rtfData: Data?
    var string: String?
    var fileURLs: [URL]
    var hasImage: Bool
}

/// 分类结果：描述应入库的数据形态
enum Classification: Equatable {
    case rtf(text: String, rtfData: Data)
    case file(paths: [String], displayName: String)
    case color(text: String, hex: String)
    case url(text: String)
    case text(text: String)
    case image
}

/// 剪贴板内容分类器（纯函数，无副作用）
enum ClipboardClassifier {

    /// 按优先级分派：RTF → 文件引用 → 文本（颜色/URL/普通）→ 图片
    static func classify(_ snapshot: PasteboardSnapshot) -> Classification? {
        if let rtfData = snapshot.rtfData {
            let text = snapshot.string ?? NSLocalizedString("富文本", comment: "")
            return .rtf(text: text, rtfData: rtfData)
        }

        if !snapshot.fileURLs.isEmpty {
            let paths = snapshot.fileURLs.map { $0.path }
            let names = paths.map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
            return .file(paths: paths, displayName: names)
        }

        if let text = snapshot.string, !text.isEmpty {
            if text.range(of: "^#?([A-Fa-f0-9]{6}|[A-Fa-f0-9]{3})$", options: .regularExpression) != nil {
                let hex = text.hasPrefix("#") ? text : "#\(text)"
                return .color(text: text, hex: hex)
            }
            if let url = URL(string: text), url.scheme == "http" || url.scheme == "https" {
                return .url(text: text)
            }
            return .text(text: text)
        }

        if snapshot.hasImage {
            return .image
        }
        return nil
    }
}

/// 敏感内容过滤：密码管理器暗标记 + 自定义正则
enum SensitiveFilter {

    /// 标记为「隐藏/自动生成」的剪贴板类型，出现即忽略整条内容
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.1password.concealed-type",
        "org.nspasteboard.AutoGeneratedType"
    ]

    static func isConcealed(_ typeIdentifiers: [String]) -> Bool {
        concealedTypes.contains(where: typeIdentifiers.contains)
    }

    /// patternsString 为换行分隔的正则表达式（与设置页格式一致）。
    /// 不用逗号分隔：正则表达式本身常含逗号（如量词 {13,16}），会被误切分。
    static func matchesSensitiveRegex(_ text: String, patternsString: String) -> Bool {
        let patterns = patternsString
            .components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
        return patterns.contains { pattern in
            text.range(of: pattern, options: .regularExpression) != nil
        }
    }
}
